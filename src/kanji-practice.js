export function buildKanjiWords(cards,vocab){
 const index=new Map(vocab.filter(v=>v.ready==='true').map(v=>[v.japanese+'|'+v.reading,v.french]));
 const known=new Set(cards.map(c=>c.character));
 return new Map(cards.map(c=>{
  const byReading=new Map();
  function add(family,jp,kana,fr,hint){
   if(byReading.has(family)||!jp.includes(c.character)||!fr)return;
   if(!hint&&[...jp].some(ch=>/\p{Script=Han}/u.test(ch)&&!known.has(ch))){
    // Keep the target written, never reveal its kana. Only split when the
    // reading at the target's edge is certain, e.g. target + unknown suffix.
    if(jp.startsWith(c.character)&&kana.startsWith(family))hint=c.character+kana.slice(family.length);
    else if(jp.endsWith(c.character)&&kana.endsWith(family))hint=kana.slice(0,-family.length)+c.character;
   }
   byReading.set(family,{jp,kana,fr,hint:hint&&hint!==jp?hint:''});
  }
  for(const [k,f,j,r,t,h] of curated)if(k===c.character)add(f,j,r,t,h);
  // Only use a catalogue example when its spelling AND pronunciation have a translation.
  for(const line of c.examples.split('\n')){
   const m=line.match(/^([^：]+)：(.+)（([^）]+)）$/u);if(!m)continue;
   const [,f,j,r]=m;add(f,j,r,index.get(j+'|'+r));
  }
  // Supplement missing readings from vocabulary when the target is the sole kanji:
  // literal kana on either side lets us isolate its actual pronunciation.
  for(const f of c.readings.split('・')){
   if(byReading.has(f))continue;
   for(const v of vocab){
    if(v.ready!=='true')continue;
    const [a,b,...rest]=v.japanese.split(c.character);
    if(b===undefined||rest.length||!/^[ぁ-ゖ]*$/u.test(a+b))continue;
    if(v.reading===a+f+b){add(f,v.japanese,v.reading,v.french);break;}
   }
  }
  return [c.character,[...byReading.values()].map(w=>({...w,front:w.hint?w.jp+'（'+w.hint+'）':w.jp}))];
 }));
}

export function kanjiQueue(cards,words,states,limit,now,start=0){
 const saved=new Map(states.map(s=>[s.id,s]));const used=new Set();
 const groups=cards.filter(c=>c.ready==='true').map((card,i)=>{
  const base='kanji:'+card.character+':';const entries=[];
  function option(id,direction,word){const s=saved.get(id),due=s?Date.parse(s.card.due):-Infinity;return {card,word,direction,stateId:id,due,learned:!!s};}
  for(const d of ['writing','jp_to_fr']){const e=option(base+d,d);if(e.due<=now)entries.push(e);}
  for(const [n,w] of (words.get(card.character)||[]).entries()){
   const key=base+'word:'+w.jp+':'+w.kana+':';
   const dirs=(i+n+start)%2?['fr_to_jp','jp_to_fr']:['jp_to_fr','fr_to_jp'];
   const opts=dirs.map(d=>option(key+d,d,w)).filter(e=>e.due<=now);
   opts.sort((a,b)=>Number(b.learned)-Number(a.learned)||(a.learned?a.due-b.due:0));
   if(opts.length)entries.push(opts[0]);
  }
  const due=Math.min(...entries.filter(e=>e.learned).map(e=>e.due));
  return {entries,due};
 }).filter(g=>g.entries.length).sort((a,b)=>a.due-b.due);
 const picked=[];let count=0;
 for(const g of groups){
  const local=new Set(used);
  const distinct=g.entries.filter(e=>{if(!e.word)return true;if(local.has(e.word.jp))return false;local.add(e.word.jp);return true;});
  if(!distinct.length)continue;
  if(limit!==Infinity&&picked.length>=5)break;
  if(count+distinct.length>limit&&count)break;
  const part=distinct.slice(0,limit-count);picked.push(part);count+=part.length;
  for(const e of part)if(e.word)used.add(e.word.jp);
  if(count>=limit)break;
 }
 // Writing first; interleave targets so a revealed character is not a drawing hint.
 const out=[];for(let n=0;picked.some(g=>g[n]);n++)for(const g of picked)if(g[n])out.push(g[n]);
 return out;
}
